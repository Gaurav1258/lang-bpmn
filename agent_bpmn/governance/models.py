from datetime import datetime, timezone
import hashlib
import json
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from agent_bpmn.simulation.models import SimulationReport


class UserPrincipal(BaseModel):
    """
    Authenticated enterprise user identity with Okta / OIDC claims.
    """
    user_id: str
    email: str
    name: str
    department: str
    roles: List[str] = Field(default_factory=list)  # e.g. ["role:compliance_officer", "role:developer"]
    permissions: List[str] = Field(default_factory=list)  # e.g. ["workflow:propose", "task:approve"]

    def has_role(self, role: str) -> bool:
        if "role:admin" in self.roles:
            return True
        return role in self.roles

    def has_permission(self, permission: str) -> bool:
        if "role:admin" in self.roles:
            return True
        return permission in self.permissions


class ChangeProposalRequest(BaseModel):
    """
    Submitted proposal from a manager to alter a workflow's topology or DMN rules.
    """
    workflow_id: str
    target_version: str
    author_email: str
    business_justification: str
    candidate_yaml: str
    assigned_reviewers: List[str] = Field(default_factory=list)
    simulation_report: Optional[SimulationReport] = None


class ChangeProposal(BaseModel):
    """
    Git-backed Pull Request representation generated by the governance engine.
    """
    proposal_id: str
    workflow_id: str
    target_version: str
    author_email: str
    business_justification: str
    branch_name: str
    pr_number: int
    pr_title: str
    pr_body_markdown: str
    status: str = "PENDING_REVIEW"  # "PENDING_REVIEW", "APPROVED", "MERGED", "REJECTED"
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    approved_by: Optional[str] = None
    merged_at: Optional[str] = None


class AuditTrailEntry(BaseModel):
    """
    Tamper-evident, cryptographically chained audit log entry for SOC2 & regulatory audits.
    """
    entry_id: str
    index: int
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    actor: str
    action: str  # "PROPOSE_CHANGE", "APPROVE_TASK", "REJECT_TASK", "SIMULATION_RUN", "MERGE_PR"
    workflow_id: str
    details: Dict[str, Any] = Field(default_factory=dict)
    previous_hash: str
    current_hash: str = ""

    def calculate_hash(self) -> str:
        """Computes SHA-256 cryptographic digest binding previous entry and current state."""
        raw_payload = {
            "index": self.index,
            "timestamp": self.timestamp,
            "actor": self.actor,
            "action": self.action,
            "workflow_id": self.workflow_id,
            "details": self.details,
            "previous_hash": self.previous_hash,
        }
        serialized = json.dumps(raw_payload, sort_keys=True)
        return hashlib.sha256(serialized.encode("utf-8")).hexdigest()
